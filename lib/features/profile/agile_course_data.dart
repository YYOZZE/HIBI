class AgileLesson {
  const AgileLesson({
    required this.id,
    required this.title,
    required this.duration,
    required this.goal,
    required this.explanation,
    required this.keyPoints,
    required this.practice,
    required this.deliverable,
    required this.checklist,
    this.caseStudy,
    this.commonPitfalls = const [],
    this.practiceSteps = const [],
    this.template,
    this.quiz,
    this.references = const [],
  });

  final String id;
  final String title;
  final int duration;
  final String goal;
  final List<String> explanation;
  final List<String> keyPoints;
  final String practice;
  final String deliverable;
  final List<String> checklist;
  final AgileCaseStudy? caseStudy;
  final List<String> commonPitfalls;
  final List<String> practiceSteps;
  final AgileTemplate? template;
  final AgileQuizQuestion? quiz;
  final List<String> references;
}

class AgileCaseStudy {
  const AgileCaseStudy({
    required this.title,
    required this.situation,
    required this.decision,
    required this.outcome,
    this.reflection = const [],
  });

  final String title;
  final String situation;
  final String decision;
  final String outcome;
  final List<String> reflection;
}

class AgileTemplate {
  const AgileTemplate({
    required this.title,
    required this.content,
    required this.example,
  });

  final String title;
  final String content;
  final String example;
}

class AgileQuizQuestion {
  const AgileQuizQuestion({
    required this.question,
    required this.options,
    required this.correctIndex,
    required this.explanation,
  });

  final String question;
  final List<String> options;
  final int correctIndex;
  final String explanation;
}

